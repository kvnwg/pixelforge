"""Refresh out/examples/: finished exports a game (or a person) can pick up without running
anything: one character per rig, the Stone Warden boss and the FX set (ROADMAP.md Phase 10).

Run after `pf build --all` and `pf fx build --all`:
    .venv/bin/python tools/make_examples.py
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "out"
EXAMPLES = OUT / "examples"
PICKS = [  # (name, why it is here, the GIF to keep)
    ("knight", "the player knight (humanoid, small): the full combat set", "attack_heavy_e"),
    ("rk_ranger", "a Rolling Knight class: bow, backflip", "shoot_bow_e"),
    ("slime", "blob rig: squash and stretch, hop, spit", "attack_spit_e"),
    ("bat", "flyer rig: hovers over a grounded pivot", "attack_swoop_e"),
    ("wolf", "quadruped rig: bite, a howl with the snout to the sky", "howl_e"),
    ("goblin_archer", "humanoid_small rig: a goblin archer on the enemy profile", "shoot_bow_e"),
    ("ogre", "humanoid_large rig on the medium 48 px canvas: overhead slam, roar", "attack_heavy_e"),
    ("stone_warden", "golem rig on the large 64 px canvas: the first boss, six moves", "attack_slam_e"),
]


def main() -> None:
    if EXAMPLES.exists():
        shutil.rmtree(EXAMPLES)
    EXAMPLES.mkdir(parents=True)
    rows = []
    for name, why, gif in PICKS:
        src, dst = OUT / name, EXAMPLES / name
        dst.mkdir()
        for f in (f"{name}.png", f"{name}.json", f"{name}_{gif}.gif"):
            shutil.copy2(src / f, dst / f)
        pf = json.loads((src / f"{name}.json").read_text())["meta"]["pixelforge"]
        anims = sorted(pf["loop"])
        rows.append(f"| [`{name}`]({name}/) | {pf['rig']} | {pf['size_class']} | {pf['pivot']} | "
                    f"{pf['timing_profile']} | {why} | {len(anims)} |")
    shutil.copytree(OUT / "fx", EXAMPLES / "fx", ignore=shutil.ignore_patterns("*.gif"))
    fx = json.loads((OUT / "fx" / "index.json").read_text())["fx"]
    readme = [
        "# Example exports",
        "",
        "Finished pixelforge exports, regenerated by `tools/make_examples.py` (run `pf build --all` "
        "and `pf fx build --all` first). Each character is a PNG spritesheet plus Aseprite-format "
        "JSON with combat data in `meta.pixelforge`, and one GIF to look at. Load them with the "
        "code in `loaders/` (see the README at the repo root).",
        "",
        "| Character | Rig | Size class | Pivot | Timing | What it shows | Animations |",
        "|---|---|---|---|---|---|---|",
        *rows,
        "",
        f"`fx/`: the FX library, {len(fx)} effects, each a sheet plus JSON with its pivot per tag "
        "(`<anim>_<dir>`), layer, space and loops; `fx/index.json` lists them.",
        "",
    ]
    (EXAMPLES / "README.md").write_text("\n".join(readme))
    total = sum(p.stat().st_size for p in EXAMPLES.rglob("*") if p.is_file())
    print(f"examples: {len(PICKS)} characters and {len(fx)} FX in {EXAMPLES} ({total // 1024} KB)")


if __name__ == "__main__":
    main()
